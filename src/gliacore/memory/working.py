"""
Working Memory for Active Task State in NEURON
Lightweight in-memory scratchpad tracking intermediate reasoning steps.
"""

from typing import Dict, List, Any, Optional
from dataclasses import dataclass, field
import time


@dataclass
class WorkingMemoryArtifact:
    artifact_id: str
    source_neuron: str
    timestamp: float
    data_type: str
    content: Any
    confidence: float = 1.0


class WorkingMemory:
    """
    Scratchpad memory storing the current execution state,
    intermediate hypotheses, and validated reasoning steps.
    """

    def __init__(self, task_id: str):
        self.task_id = task_id
        self.created_at = time.time()
        self.artifacts: List[WorkingMemoryArtifact] = []
        self.shared_state: Dict[str, Any] = {}

    def add_artifact(self, artifact_id: str, source_neuron: str, data_type: str, content: Any, confidence: float = 1.0) -> None:
        """Record an intermediate artifact generated by a neuron."""
        art = WorkingMemoryArtifact(
            artifact_id=artifact_id,
            source_neuron=source_neuron,
            timestamp=time.time(),
            data_type=data_type,
            content=content,
            confidence=confidence
        )
        self.artifacts.append(art)

    def get_latest(self, data_type: Optional[str] = None) -> Optional[WorkingMemoryArtifact]:
        """Retrieve the most recent artifact, optionally filtered by type."""
        for art in reversed(self.artifacts):
            if data_type is None or art.data_type == data_type:
                return art
        return None

    def get_all(self, data_type: Optional[str] = None) -> List[WorkingMemoryArtifact]:
        """Retrieve all artifacts matching data_type."""
        if data_type is None:
            return list(self.artifacts)
        return [art for art in self.artifacts if art.data_type == data_type]

    def set_state(self, key: str, value: Any) -> None:
        """Set a global state key for the current task."""
        self.shared_state[key] = value

    def get_state(self, key: str, default: Any = None) -> Any:
        """Get a global state key."""
        return self.shared_state.get(key, default)

    def summary(self) -> Dict[str, Any]:
        """Return structured summary of working memory."""
        return {
            "task_id": self.task_id,
            "artifact_count": len(self.artifacts),
            "state_keys": list(self.shared_state.keys()),
            "artifacts_summary": [
                {"id": a.artifact_id, "neuron": a.source_neuron, "type": a.data_type, "confidence": a.confidence}
                for a in self.artifacts
            ]
        }
